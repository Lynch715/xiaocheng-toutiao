function standPhoneCall(stand, seed, key) {
  const reason = stand.reason;
  if (!reason || !STAND_PHONE_REASONS[reason.key] || !Number.isFinite(reason.value)) {
    throw new Error('报摊回报缺少实际销量贡献');
  }
  const variants = STAND_PHONE_REASONS[reason.key][reason.value >= 0 ? 'positive' : 'negative'];
  const variant = Math.floor(randomAt(seed, key + '/phone') * variants.length);
  const remaining = stand.printed - stand.sold;
  const status = stand.printed === 0 ? '没分到报纸' :
    stand.stockout && stand.time ? stand.time + '就卖光了' :
    remaining === 0 ? '这批' + stand.sold + '份刚好卖完' :
    '卖出' + stand.sold + '份，还剩' + remaining + '份';
  const cause = reason.key === 'topic' && reason.value > 0 && reason.topicLocal === 0 ? [
    '本期城里正在关心' + reason.section + '消息',
    '这期的' + reason.section + '话题正热，带来了读者',
    '赶上城里关注' + reason.section + '这件事，报纸跟着好卖'][variant] : variants[variant](reason);
  return stand.name + status + (stand.stockout && reason.value < 0 ? '，不过' : '，') + cause + '。';
}
