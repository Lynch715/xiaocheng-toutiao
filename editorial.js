// 只让新增猛料细节的来路存疑，原有常规事实与读者追踪线索不变。
function rumorFieldNote(story) {
  const detail = story.scoop.report.join('').replaceAll('记者', '在场的人');
  return '新打听到的细节来自转述：' + detail +
    '问到谁在现场，几个人说法不一，最早讲这段的人还没联系上。';
}

function verificationCopy(story, report) {
  if (!report?.verified) return [];
  const note = DESK_NOTES[story.id];
  if (report.checkResult === 'confirmed') {
    const correction = story.risk ? [story.risk.brief] : [];
    if (report.rumor || report.tier === 'scoop') {
      return [...correction, '记者重新找到当事人逐项对过，《' + story.scoop.title + '》中的新增细节能够对上，原话与现场记录都留在编辑部。', note.source];
    }
    return [...correction, note.source];
  }
  if (report.checkResult === 'deflated') {
    if (story.risk) return [story.risk.brief, note.source,
      '传来的那段说法没有找到能对上的凭据，编辑把它划去了。这次先把查清的经过写全。'];
    return ['记者补问了当事人，新增细节没有得到确认。原来记下的经过仍能对上，成稿保留下面这些。',
      note.source];
  }
  return [note.source];
}

